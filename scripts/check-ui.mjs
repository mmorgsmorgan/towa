import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { chromium } from '@playwright/test';

const origin=process.argv[2]||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,...(process.argv[3]?{executablePath:process.argv[3]}:{})});
const errors=[];
const browserErrors=[];
let page;
try{
  page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')browserErrors.push(message.text());});
  page.on('requestfailed',request=>browserErrors.push(request.url()+': '+request.failure()?.errorText));
  const response=await page.goto(origin,{waitUntil:'networkidle',timeout:30000});assert.equal(response.status(),200);
  await page.waitForFunction(()=>document.getElementById('stat-collections').textContent!=='—');
  assert.match(await page.title(),/Towa/);
  assert.equal(await page.locator('h3').filter({hasText:'Offers on individual NFTs'}).count(),1);
  assert.equal(await page.locator('form').count(),0);
  assert.equal(await page.locator('#mcp-endpoint').textContent(),origin+'/mcp');
  await page.context().grantPermissions(['clipboard-read','clipboard-write'],{origin});
  await page.locator('#copy-mcp-config').click();
  const copied=JSON.parse(await page.evaluate(()=>navigator.clipboard.readText()));
  assert.equal(copied.mcpServers.towa.url,origin+'/mcp');
  assert.equal(copied.mcpServers.towa.type,'http');
  assert.equal(copied.mcpServers.towa.headers.Authorization,'Bearer YOUR_TOWA_SESSION_TOKEN');
  await page.evaluate(()=>window.scrollTo(0,0));
  assert.ok(!/sign in with chatgpt|log in with chatgpt/i.test(await page.locator('body').innerText()));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desktop overflows horizontally.');
  await page.screenshot({path:new URL('../outputs/towa-live-desktop.png',import.meta.url).pathname});
  const routes=['/.well-known/agent-card.json','/agent.md','/architecture.md','/economy.md','/security.md','/openapi.json','/downloads/towa-agent-0.4.0.tgz','/downloads/towa-agent-0.4.0.tgz.sha256'];
  for(const route of routes)assert.equal((await page.request.get(origin+route)).status(),200,route+' is missing.');
  const spec=await (await page.request.get(origin+'/openapi.json')).json();
  assert.ok(spec.components.schemas.NftOfferInput.required.includes('itemId'));
  assert.equal(spec.components.schemas.NftOfferInput.additionalProperties,false);
  assert.ok(spec.paths['/mcp'].post);
  assert.ok(spec.paths['/v1/mcp/sessions'].post);
  const discovery=await (await page.request.get(origin+'/.well-known/agent-card.json')).json();
  assert.equal(discovery.mcp.url,origin+'/mcp');
  assert.equal(discovery.mcp.authentication.oauth,false);
  const bytes=await (await page.request.get(origin+'/downloads/towa-agent-0.4.0.tgz')).body();
  const checksum=await (await page.request.get(origin+'/downloads/towa-agent-0.4.0.tgz.sha256')).text();
  assert.equal(checksum.split(' ')[0],createHash('sha256').update(bytes).digest('hex'));
  assert.deepEqual(bytes,await readFile(new URL('../dist/downloads/towa-agent-0.4.0.tgz',import.meta.url)));
  assert.equal((await page.request.get(origin+'/v1/agents/me')).status(),401);
  assert.equal((await page.request.get(origin+'/v1/mcp/sessions')).status(),401);
  for(const route of ['/data/tower.sqlite','/data/credential-key','/lib/identities.mjs','/wallet.mjs','/legacy/index.html'])assert.equal((await page.request.get(origin+route)).status(),404);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflows horizontally.');
  await page.screenshot({path:new URL('../outputs/towa-live-mobile.png',import.meta.url).pathname});
  assert.deepEqual(errors,[]);
  const report={origin,at:new Date().toISOString(),publicWithoutSignIn:true,desktopAndMobile:true,hostedMcpConfiguration:true,individualNftOffers:true,downloadAndChecksum:true,apiSchema:true,privateRoutesProtected:true,javascriptErrors:errors};
  await writeFile(new URL('../outputs/ui-smoke.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
}catch(error){
  if(page)await page.screenshot({path:new URL('../outputs/ui-failure.png',import.meta.url).pathname}).catch(()=>{});
  console.error(JSON.stringify({error:error.message,javascriptErrors:errors,browserErrors}));
  throw error;
}finally{await browser.close();}
